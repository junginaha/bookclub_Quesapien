-- 라이브 DB를 curl로 직접 조회해 확인한 실제 버그: schedule 컬럼에
-- "20206년 6월 27일 토요일 오후 2시"라고 저장돼 있다(연도 "20206" — 자릿수 오타).
-- parseKoreanSchedule()의 정규식은 정확히 4자리 뒤에 "년"을 기대하므로
-- ("20206"은 4자리 뒤에 "6"이 와서) 이 문자열을 파싱하지 못하고, 이 클럽은
-- event_starts_at도 비어있어 항상 시작일 미상("다시 함께 읽어요")으로 빠진다.
-- 다른 5건(다정함의-발명 등)은 schedule/event_starts_at 자체가 아예 비어있어
-- 오타가 아니라 실제 일정 데이터 입력이 필요한 건 — 이 마이그레이션은 건드리지 않는다.

UPDATE landing_book_clubs
SET schedule = '2026년 6월 27일 토요일 오후 2시'
WHERE slug = '최신간-북토크'
  AND schedule = '20206년 6월 27일 토요일 오후 2시';
